/**
 * 基础语言特性增强工具包（Language Utilities）。
 *
 * <p>本包作为对 Java 原生核心语法的补充，提供了一系列无状态、线程安全的通用工具类。
 * 涵盖字符串处理（StrUtils）、数字转换（NumberUtils）、对象操作（ObjectUtils）以及反射增强等。
 *
 * <p><b>设计原则：</b>
 *
 * <ul>
 *   <li><b>高通用性：</b> 仅包含不带任何业务属性的纯技术底层工具。
 *   <li><b>无状态与线程安全：</b> 所有工具类均不允许被实例化，且其对外提供的方法必须是线程安全的静态方法。
 *   <li><b>防御性编程：</b> 内部应对边界条件（如空指针、越界等）做完善的健壮性处理，避免向调用方抛出意外的运行时异常。
 * </ul>
 *
 * @author jasper
 * @since 1.0.0
 */
